import { test, expect } from '@playwright/test';
import { realpathSync, mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
let root: string;
let projectId: string;
test.beforeAll(async () => {
 root = realpathSync(mkdtempSync(join(tmpdir(), 'atlas-e2e-')));
 mkdirSync(join(root, 'app/login'), { recursive: true });
 mkdirSync(join(root, 'app/api/login'), { recursive: true });
 writeFileSync(join(root, 'app/login/page.tsx'), 'export default function LoginPage() { return <form><label>Email<input name="email" placeholder="Email" /></label><button type="submit">Se connecter</button></form>; }\n');
 writeFileSync(join(root, 'app/api/login/route.ts'), 'export async function POST(request: Request) { const body = await request.json(); return Response.json({ authenticated: Boolean(body.email) }); }\n');
 writeFileSync(join(root, 'entry.ts'), "import { forward } from './sink';\nexport function handle(req: Request) {\n const value = req.query.value;\n forward(value);\n}\n");
 writeFileSync(join(root, 'sink.ts'), "export function forward(query: string) {\n db.query(query);\n}\n");
 writeFileSync(join(root, 'package.json'), JSON.stringify({ dependencies: { next: '^15', react: '^19' } }));
 writeFileSync(join(root, 'auth.ts'), 'export function login(email: string) { return email.length > 0; }\n');
 execFileSync('git', ['init', root]); execFileSync('git', ['-C', root, 'add', '.']); execFileSync('git', ['-C', root, '-c', 'user.name=Atlas test', '-c', 'user.email=test@example.invalid', 'commit', '-m', 'fixture']);
 writeFileSync(join(root, 'auth.ts'), 'export function login(email: string) { return email.includes("@"); }\n');
});
