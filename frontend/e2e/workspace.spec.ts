 await expect(page.locator('.chat-message.assistant')).toHaveCount(1);
 await expect(page.getByRole('dialog')).toBeVisible(); await page.keyboard.press('Escape');
 await page.getByRole('button', { name: 'Quels tests manquent ?', exact: true }).click();
 await expect(page.getByRole('heading', { name: 'Tests & scénarios' })).toBeVisible();
 await expect(page.getByText('Couverture fonctionnelle vérifiée')).toBeVisible();
 const nav = page.getByRole('navigation', { name: 'Navigation principale' });
 await nav.getByRole('button', { name: 'Estimation', exact: true }).click();
 await page.getByLabel('Mission', { exact: true }).fill('Modifier login pour ajouter du 2FA');
 await page.getByRole('button', { name: 'Estimer', exact: true }).click();
 await expect(page.getByRole('table')).toBeVisible();
 await expect(page.getByRole('heading', { name: 'Tests à prévoir' })).toBeVisible();
 await page.screenshot({ path: '../output/playwright/estimate.png', fullPage: true });
